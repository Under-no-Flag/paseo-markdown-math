import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const cssFile = require.resolve('katex/dist/katex.min.css');
let css = await readFile(cssFile, 'utf8');
// Keep only WOFF2 and inline it: no CDN, daemon URL, or runtime CSS loader.
css = css.replace(/src:[^;}]+(?=;|})/g, (src) => {
  const match = src.match(/url\(([^)]+\.woff2)\) format\(["']woff2["']\)/);
  if (!match) throw new Error('KaTeX font declaration has no WOFF2 source');
  return `src:url(${match[1]}) format("woff2")`;
});
const files = [...new Set([...css.matchAll(/url\(([^)]+\.woff2)\)/g)].map(m => m[1]))];
for (const file of files) {
  const bytes = await readFile(resolve(dirname(cssFile), file));
  css = css.replaceAll(`url(${file})`, `url(data:font/woff2;base64,${bytes.toString('base64')})`);
}
await mkdir('client/generated', { recursive: true });
await writeFile('client/generated/katex-css.ts', `// Generated by npm run assets. Do not edit.\nexport const katexCss = ${JSON.stringify(css)};\n`);
console.log(`Bundled ${files.length} KaTeX fonts (${css.length} CSS characters).`);

const { build } = await import('esbuild');
const runtime = await build({entryPoints:['scripts/frame-runtime.ts'],bundle:true,write:false,format:'iife',platform:'browser',target:'es2020',minify:true,legalComments:'inline'});
await writeFile('client/generated/frame-runtime.ts', `// Generated browser runtime. Runs only inside the isolated preview frame.\nexport const frameRuntime = ${JSON.stringify(runtime.outputFiles[0].text)};\n`);
console.log(`Bundled Mermaid iframe runtime (${runtime.outputFiles[0].text.length} characters).`);
